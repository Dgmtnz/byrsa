import 'dart:io';
import 'dart:math' as math;
import 'dart:typed_data';

import 'package:image/image.dart' as img;

/// Generates document pages whose clean original is known.
///
/// **This is not a substitute for the fifty photographs.** It cannot be: real
/// captures have paper grain, lens blur, sensor noise, JPEG artefacts and
/// lighting no formula reproduces, and the headline metric over the real set is
/// character error rate, which needs an OCR engine and real glyphs.
///
/// What it is for is the thing that was missing: the harness had never executed
/// the pipeline over anything at all. A corpus with a known clean original lets
/// the plumbing run today, gives every restoration change a numeric regression
/// guard, and means that when the photographs arrive the tooling is already
/// debugged instead of being debugged at the worst moment.
///
/// The two shadow models come from a real finding. A purely multiplicative
/// shadow is exactly what dividing by an estimated background inverts, so
/// measuring only against that flatters the classical pipeline. The physical
/// model adds ambient light and a colour cast, which it does not invert.
/// See DECISIONS.md D-039.
class SyntheticCorpus {
  const SyntheticCorpus({
    this.width = 1024,
    this.height = 1400,
    this.seed = 20260913,
  });

  final int width;
  final int height;
  final int seed;

  /// Writes [count] documents plus a manifest into [directory].
  ///
  /// Returns the manifest text, so a caller can diff it rather than re-reading
  /// the file it just wrote.
  String write(Directory directory, {int count = 10}) {
    final images = Directory('${directory.path}/images')
      ..createSync(recursive: true);
    final clean = Directory('${directory.path}/ground_truth_image')
      ..createSync(recursive: true);
    final text = Directory('${directory.path}/ground_truth')
      ..createSync(recursive: true);

    final documents = <String>[];
    for (var i = 0; i < count; i++) {
      final shadow = i.isEven ? _Shadow.multiplicative : _Shadow.physical;
      final id =
          'synthetic-${(i + 1).toString().padLeft(2, '0')}-${shadow.name}';
      final page = _page(seed + i * 977);

      File('${images.path}/$id.jpg').writeAsBytesSync(
          img.encodeJpg(_shade(page, shadow, seed + i), quality: 92));
      File('${clean.path}/$id.png').writeAsBytesSync(img.encodePng(page));
      // Empty on purpose: no font is rendered here, so there is no text an OCR
      // engine could be expected to recover. The dataset README says so.
      File('${text.path}/$id.txt').writeAsStringSync('');

      documents.add('''
    {
      "id": "$id",
      "file": "images/$id.jpg",
      "groundTruth": "ground_truth/$id.txt",
      "groundTruthImage": "ground_truth_image/$id.png",
      "category": "synthetic",
      "language": "none",
      "conditions": ["${shadow.name}-shadow"],
      "publish": true,
      "license": "CC0-1.0"
    }''');
    }

    final manifest = '''
{
  "version": 1,
  "comment": "Generated by `harness synth`. NOT the evaluation set. These pages exist so the pipeline can be run and regressions caught before the fifty photographs exist; they have a clean original and no text. See DECISIONS.md D-041.",
  "documents": [
${documents.join(',\n')}
  ]
}
''';
    File('${directory.path}/manifest.json').writeAsStringSync(manifest);
    return manifest;
  }

  /// A page of ruled text blocks on off-white paper, with grain.
  img.Image _page(int pageSeed) {
    final random = math.Random(pageSeed);
    final image = img.Image(width: width, height: height, numChannels: 3);
    final lineHeight = math.max(3, height ~/ 110);
    final margin = width ~/ 9;

    for (var y = 0; y < height; y++) {
      for (var x = 0; x < width; x++) {
        final grain = random.nextInt(9) - 4;
        final value = (245 + grain).clamp(0, 255);
        image.setPixelRgb(x, y, value, value, (value - 4).clamp(0, 255));
      }
    }

    var y = height ~/ 10;
    while (y < height - height ~/ 10) {
      // Paragraph breaks, so the page is not a uniform texture.
      if (random.nextInt(7) == 0) {
        y += lineHeight * 3;
        continue;
      }
      final right = width - margin - random.nextInt(width ~/ 5);
      for (var ty = y; ty < y + lineHeight && ty < height; ty++) {
        for (var x = margin; x < right; x++) {
          // Broken along the line so it reads as words rather than a rule.
          if ((x ~/ math.max(4, lineHeight)) % 5 == 4) continue;
          final ink = 28 + random.nextInt(22);
          image.setPixelRgb(x, ty, ink, ink, ink + 6);
        }
      }
      y += lineHeight * 3;
    }
    return image;
  }

  /// Applies a shadow to a clean page.
  img.Image _shade(img.Image page, _Shadow shadow, int shadeSeed) {
    final out = img.Image(width: width, height: height, numChannels: 3);
    final random = math.Random(shadeSeed);
    final edge = 0.45 + random.nextDouble() * 0.25;
    final softness = 0.04 + random.nextDouble() * 0.06;

    for (var y = 0; y < height; y++) {
      for (var x = 0; x < width; x++) {
        final pixel = page.getPixel(x, y);
        final u = x / width;
        final v = y / height;
        // A soft gradient across the page plus a hand-shadow edge.
        final gradient = 0.55 + 0.45 * u;
        final t = ((u + 0.35 * v - edge) / softness).clamp(-1.0, 1.0);
        final penumbra = 0.5 - 0.5 * t;

        double r = pixel.r.toDouble();
        double g = pixel.g.toDouble();
        double b = pixel.b.toDouble();

        if (shadow == _Shadow.multiplicative) {
          final k = gradient * (1.0 - 0.45 * penumbra);
          r *= k;
          g *= k;
          b *= k;
        } else {
          // Attenuation, additive ambient light, and the blue cast a real
          // shadow has. Dividing by an estimated background does not undo it.
          final k = gradient * (1.0 - 0.62 * penumbra);
          final ambient = 14.0 * penumbra;
          r = r * k * (1.0 - 0.10 * penumbra) + ambient;
          g = g * k * (1.0 - 0.04 * penumbra) + ambient;
          b = b * k * (1.0 + 0.06 * penumbra) + ambient;
        }
        out.setPixelRgb(x, y, r.round().clamp(0, 255), g.round().clamp(0, 255),
            b.round().clamp(0, 255));
      }
    }
    return out;
  }
}

enum _Shadow {
  multiplicative,
  physical;
}

/// Peak signal-to-noise ratio in dB, over the luma of two images of equal size.
///
/// Returns null rather than infinity when the images are identical, because an
/// infinite score in a report is a bug that looks like a triumph.
double? psnr(Uint8List a, Uint8List b, {int channels = 3}) {
  if (a.length != b.length || a.isEmpty) return null;
  var total = 0.0;
  for (var i = 0; i < a.length; i++) {
    final difference = a[i] - b[i];
    total += difference * difference;
  }
  final mse = total / a.length;
  if (mse <= 0) return null;
  return 10 * (math.log(255 * 255 / mse) / math.ln10);
}
