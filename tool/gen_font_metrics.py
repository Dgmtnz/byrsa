"""Generate lib/src/font_metrics.dart from Adobe's Helvetica.afm.

Widths are facts from the Adobe Core-14 metrics, not measurements of ours.
Re-run only when the encoding or the font choice changes (see DECISIONS.md D-009).

Usage: python3 tool/gen_font_metrics.py <path/to/Helvetica.afm>
"""
import re
import sys

from fontTools.agl import AGL2UV

AFM = sys.argv[1] if len(sys.argv) > 1 else (
    "/usr/lib/python3.14/site-packages/matplotlib/mpl-data/fonts/pdfcorefonts/Helvetica.afm"
)

# WinAnsiEncoding is CP1252, with these documented deviations (PDF 1.7, Annex D.2):
#  - 0xA0 is a non-breaking space that behaves as 'space'
#  - 0xAD is a soft hyphen that behaves as 'hyphen'
#  - codes 0x80..0x9F that CP1252 leaves undefined map to 'bullet' in Acrobat
WINANSI_OVERRIDES = {0xA0: 0x0020, 0xAD: 0x002D}

# fontTools' AGL table is missing these three Adobe glyph names, and "m2" is
# too common in real Spanish documents to lose to a '?'.
EXTRA_GLYPH_NAMES = {
    "onesuperior": 0x00B9,
    "twosuperior": 0x00B2,
    "threesuperior": 0x00B3,
}

widths_by_name = {}
header = {}
with open(AFM, "r", encoding="latin-1") as fh:
    for line in fh:
        m = re.match(r"^C\s+(-?\d+)\s*;\s*WX\s+(-?\d+)\s*;\s*N\s+(\S+)\s*;", line)
        if m:
            widths_by_name[m.group(3)] = int(m.group(2))
            continue
        for key in ("Ascender", "Descender", "CapHeight", "XHeight", "FontName"):
            if line.startswith(key + " "):
                header[key] = line.split(None, 1)[1].strip()

uv_to_name = {}
for name, width in widths_by_name.items():
    uv = AGL2UV.get(name) or EXTRA_GLYPH_NAMES.get(name)
    if uv is not None and uv not in uv_to_name:
        uv_to_name[uv] = name

widths = [0] * 256
covered = {}
for code in range(32, 256):
    uv = WINANSI_OVERRIDES.get(code)
    if uv is None:
        try:
            uv = ord(bytes([code]).decode("cp1252"))
        except UnicodeDecodeError:
            continue
    name = uv_to_name.get(uv)
    if name is None:
        continue
    widths[code] = widths_by_name[name]
    covered[uv] = code

missing = [c for c in range(32, 256) if widths[c] == 0 and c not in (0x7F,)]
print(f"// {len(covered)} codes covered, missing {missing}", file=sys.stderr)

rows = []
for start in range(0, 256, 16):
    rows.append("  " + " ".join(f"{w}," for w in widths[start:start + 16]))

pairs = ", ".join(f"0x{uv:04X}: {code}" for uv, code in sorted(covered.items()))

out = f'''// SPDX-FileCopyrightText: 2026 Diego Martínez Fernández
// SPDX-License-Identifier: Apache-2.0
//
// GENERATED by tool/gen_font_metrics.py from Adobe's {header.get("FontName", "Helvetica")}.afm.
// Do not edit by hand; see DECISIONS.md D-009 for why these live as constants
// rather than as a bundled asset.

/// Glyph advance widths of Helvetica, in 1/1000 em, indexed by WinAnsi code.
///
/// A width of 0 means the code is not encodable (see [winAnsiFromRune]).
const List<int> helveticaWidths = <int>[
{chr(10).join(rows)}
];

/// Ascender of Helvetica, in 1/1000 em.
const int helveticaAscender = {header.get("Ascender", 718)};

/// Descender of Helvetica, in 1/1000 em. Negative, as in the AFM.
const int helveticaDescender = {header.get("Descender", -207)};

/// Distance from descender to ascender, in 1/1000 em.
///
/// This is what a viewer uses to size a selection rectangle, so it is what we
/// solve against when choosing a font size for a bounding box.
const int helveticaSpan = helveticaAscender - helveticaDescender;

const Map<int, int> _winAnsiFromRune = <int, int>{{{pairs}}};

/// WinAnsi byte for [rune], or `null` when the character cannot be encoded.
int? winAnsiFromRune(int rune) => _winAnsiFromRune[rune];
'''
sys.stdout.write(out)
